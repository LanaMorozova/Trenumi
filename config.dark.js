/**
 * Dark theme overrides.
 *
 * Both token files are sources here so that references like {color.dark.900}
 * resolve, but the output is filtered down to the tokens that tokens.dark.json
 * actually redefines — a token with the same value in both themes is emitted
 * once, in tokens.css, and never repeated.
 */
export default {
  // Both warnings this build raises are the point of the file, not a problem:
  // every token here deliberately collides with its light-mode twin, and the
  // primitives its references point at are filtered out because tokens.css
  // already defines them and loads first.
  log: { warnings: 'disabled' },
  usesDtcg: true,
  source: ['tokens.json', 'tokens.dark.json'],
  platforms: {
    cssDark: {
      transformGroup: 'css',
      buildPath: 'src/styles/',
      files: [{
        destination: 'tokens.dark.css',
        format: 'css/variables',
        filter: (token) => token.filePath.endsWith('tokens.dark.json'),
        options: {
          outputReferences: true,
          selector: '[data-theme="dark"]',
          fileHeader: () => [
            'Trenumi dark theme.',
            'Generated by Style Dictionary — do not edit by hand.',
            'Only the tokens that differ from the light theme appear here.'
          ]
        }
      }]
    }
  }
};
